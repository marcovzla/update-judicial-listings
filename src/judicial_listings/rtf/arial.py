def text_width_points(
    text: str,
    font_size_points: float = DEFAULT_FONT_SIZE_POINTS,
) -> float:
    """Return the width of text rendered in Arial at the given point size."""
    if font_size_points <= 0:
        raise ValueError("font size must be positive")

    normalized = unicodedata.normalize("NFKD", text)
    characters = (
        character
        for character in normalized
        if not unicodedata.combining(character)
    )

    units = 0
    for character in characters:
        try:
            units += CHARACTER_ADVANCES[character]
        except KeyError as exc:
            raise ValueError(f"unsupported Arial character: {character!r}") from exc
    return units * font_size_points / EM_UNITS
